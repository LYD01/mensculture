/**
 * Reads the live Timely service list for each shop and writes
 * `app/_constants/timelyServices.ts` (service ids, prices, durations per shop).
 *
 * Run with `pnpm timely:sync`, then `pnpm format`, and review the diff.
 * Timely serves the service picker as plain HTML, so no browser is needed.
 */
import { writeFileSync } from "node:fs";

const TIMELY_BUSINESS_ID = "301694";

const LOCATIONS = [
	{ slug: "day-street", timelyLocationId: "390542" },
	{ slug: "martin-place", timelyLocationId: "390543" },
	{ slug: "circular-quay", timelyLocationId: "389687" },
];

const OUTPUT_PATH = new URL(
	"../app/_constants/timelyServices.ts",
	import.meta.url,
);

const SERVICE_INPUT =
	/<input id="service\d+"\s+data-staffids="[^"]*"\s+data-name="([^"]*)"\s+type="checkbox"\s+name="BookableTimeSlotItemIds"\s+value="(\d+):SV"/g;

function decodeEntities(text) {
	return text
		.replace(/&amp;/g, "&")
		.replace(/&quot;/g, '"')
		.replace(/&#39;/g, "'")
		.replace(/&#183;/g, "·")
		.replace(/\s+/g, " ")
		.trim();
}

async function fetchServices({ slug, timelyLocationId }) {
	const url = `https://book.gettimely.com/Booking/Location/${TIMELY_BUSINESS_ID}?mobile=True&locationId=${timelyLocationId}`;
	const response = await fetch(url, {
		headers: { "User-Agent": "curl/8.4.0" },
	});
	if (!response.ok) {
		throw new Error(`Timely returned ${response.status} for ${slug}`);
	}
	const html = await response.text();

	const services = {};
	for (const match of html.matchAll(SERVICE_INPUT)) {
		const [, rawName, id] = match;
		const after = html.slice(match.index, match.index + 2000);
		const attrs = after.match(
			/select-list__item-attr">\s*(\d+) mins?\s*(?:&#183;|·)\s*\$(\d+(?:\.\d+)?)/,
		);
		if (!attrs) {
			throw new Error(`Could not read price for service ${id} at ${slug}`);
		}
		const name = decodeEntities(rawName);
		services[id] = {
			name,
			priceAud: Number(attrs[2]),
			durationMinutes: Number(attrs[1]),
			...(/\bfrom\b/i.test(name) ? { priceIsFrom: true } : {}),
		};
	}

	if (Object.keys(services).length === 0) {
		throw new Error(
			`No services found for ${slug}. Did Timely change its markup?`,
		);
	}
	return [slug, services];
}

const entries = await Promise.all(LOCATIONS.map(fetchServices));

const body = `// Generated by scripts/syncTimelyServices.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
import type { LocationSlug } from "./site";

export type TimelyService = {
	/** Name as shown on the Timely booking page. */
	name: string;
	priceAud: number;
	durationMinutes: number;
	/** Timely lists this as a starting price ("From"). */
	priceIsFrom?: true;
};

/** Services bookable online at each shop, keyed by Timely service id. */
export const TIMELY_SERVICES: Record<LocationSlug, Record<string, TimelyService>> = ${JSON.stringify(Object.fromEntries(entries), null, "\t")};
`;

writeFileSync(OUTPUT_PATH, body);
console.log(
	entries
		.map(
			([slug, services]) => `${slug}: ${Object.keys(services).length} services`,
		)
		.join("\n"),
);
